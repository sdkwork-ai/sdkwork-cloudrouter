use serde::{Deserialize, Serialize};

use crate::models::{OpenAiIncompleteDetails, OpenAiResponseError, OpenAiResponseOutputItem, OpenAiResponseUsage};

/// OpenAI-compatible open ai response schema exposed by Claw Router.
#[derive(Serialize, Deserialize, Debug, Clone, Default)]
pub struct OpenAiResponse {
    /// Unix timestamp in seconds when the response was created.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub created_at: Option<i64>,

    /// Error field on the open ai response, using the open ai response error module.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub error: Option<OpenAiResponseError>,

    /// Response identifier.
    pub id: String,

    /// Incomplete details field on the open ai response, using the open ai incomplete details module.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub incomplete_details: Option<OpenAiIncompleteDetails>,

    /// Model id used by the upstream response.
    pub model: String,

    /// Object type, normally response.
    pub object: String,

    /// Output items generated by the response.
    pub output: Vec<OpenAiResponseOutputItem>,

    /// Convenience text output when returned by the upstream.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub output_text: Option<String>,

    /// Response status.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub status: Option<String>,

    /// Usage field on the open ai response, using the open ai response usage module.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub usage: Option<OpenAiResponseUsage>,
}
