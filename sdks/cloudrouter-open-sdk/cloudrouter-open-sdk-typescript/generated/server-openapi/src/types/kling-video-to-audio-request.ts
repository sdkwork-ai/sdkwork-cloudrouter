import type { ProviderJsonValue } from './provider-json-value';

/** Kling video-to-sound-effect request (`POST /v1/audio/video-to-audio`). Supply `video_id` or `video_url`. */
export interface KlingVideoToAudioRequest {
  /** Enable ASMR mode to enrich detailed sound effects. */
  asmr_mode?: boolean;
  /** Prompt steering the generated background music. */
  bgm_prompt?: string;
  /** Callback URL notified when the task changes state. */
  callback_url?: string;
  /** Caller-supplied task id, unique per account. */
  external_task_id?: string;
  /** Prompt steering the generated sound effect. */
  sound_effect_prompt?: string;
  /** Id of a video generated by Kling. */
  video_id?: string;
  /** Public URL of an uploaded video. */
  video_url?: string;
}
