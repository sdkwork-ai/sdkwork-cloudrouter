#!/usr/bin/env node
// Generates per-deployment runtime secrets for the docker compose stack and
// writes them to the repository-root `.env` (git-ignored).
//
// Why this exists: docker-compose.yml no longer ships committed key material.
// The upstream credential key ring encrypts every tenant upstream credential
// at rest, so it must be unique per deployment. Run once before the first
// `docker compose up -d`:
//
//   node scripts/generate-dev-secrets.mjs
//
// The script never prints secret values. Re-running refreshes only secrets
// that are still empty in `.env`; existing values are preserved so rotation
// is always an explicit, manual act.

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(repoRoot, ".env");

function base64Key(bytes = 32) {
  return randomBytes(bytes).toString("base64");
}

function urlSafeSecret(bytes = 48) {
  return randomBytes(bytes).toString("base64url");
}

function keyRing(activeKeyId) {
  return JSON.stringify({
    activeKeyId,
    activeKey: base64Key(32),
    fingerprintKey: base64Key(32),
    decryptionKeys: [],
  });
}

const generatedSecrets = {
  CLOUDROUTER_UPSTREAM_CREDENTIAL_KEY_RING: keyRing(`key-ring-${Date.now()}`),
  CLOUDROUTER_API_KEY_PEPPER: urlSafeSecret(48),
  CLOUDROUTER_INTERNAL_GATEWAY_SIGNING_SECRET: urlSafeSecret(48),
  CLOUDROUTER_TRUSTED_SUBJECT_SECRET: urlSafeSecret(48),
  CLOUDROUTER_APP_SESSION_SECRET: urlSafeSecret(48),
};

const existingContent = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";
const existingLines = existingContent.split(/\r?\n/);
const managedKeys = new Set(Object.keys(generatedSecrets));

// Preserve every non-managed line; refresh managed lines that are still empty,
// keep managed lines that already carry a value (rotation is explicit).
const updatedLines = existingLines.map((line) => {
  const match = /^(?<key>[A-Z0-9_]+)=(?<value>.*)$/.exec(line);
  if (!match || !managedKeys.has(match.groups.key)) {
    return line;
  }
  const key = match.groups.key;
  const value = match.groups.value.trim();
  if (value.length > 0) {
    return line;
  }
  return `${key}=${generatedSecrets[key]}`;
});

const presentKeys = new Set(
  updatedLines
    .map((line) => /^(?<key>[A-Z0-9_]+)=/.exec(line)?.groups?.key)
    .filter((key) => key != null),
);
const missingKeys = [...managedKeys].filter((key) => !presentKeys.has(key));
const headerLines =
  updatedLines.filter((line) => line.trim().length > 0).length === 0
    ? [
        "# Generated by scripts/generate-dev-secrets.mjs — do not commit.",
        "# Rotation: replace a value here, then recreate dependent volumes/state.",
        "",
      ]
    : [];

const finalLines = [
  ...headerLines,
  ...updatedLines,
  ...missingKeys.map((key) => `${key}=${generatedSecrets[key]}`),
];

writeFileSync(
  envPath,
  `${finalLines.join("\n").replace(/\n{3,}/g, "\n\n")}\n`,
  { mode: 0o600 },
);

console.log(`Wrote per-deployment secrets to ${envPath}`);
console.log("Managed keys refreshed (existing non-empty values were preserved):");
for (const key of managedKeys) {
  console.log(`  - ${key}`);
}
console.log("Next step: docker compose up -d");
