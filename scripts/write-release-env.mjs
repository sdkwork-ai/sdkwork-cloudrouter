#!/usr/bin/env node

import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { RELEASE_ENVIRONMENT_CONTRACT } from './release-environment-contract.mjs';
import { releaseEnvironmentIssues } from './release-preflight.mjs';
import {
  CLAW_ROUTER_RELEASE_ENV_KEY_ORDER,
  buildClawRouterReleaseGeneratedEnv,
  completeReleaseEnvKeyOrder,
} from './dev/claw-router-application-env.mjs';

const WORKSPACE_ROOT = path.resolve(import.meta.dirname, '..');
const CONTRACT_VARIABLES = [
  ...RELEASE_ENVIRONMENT_CONTRACT.requiredReleaseEnv,
  ...RELEASE_ENVIRONMENT_CONTRACT.requiredPortalPublicEnv,
];
const OPTIONAL_CONTRACT_VARIABLES = [
  ...(RELEASE_ENVIRONMENT_CONTRACT.optionalPortalPublicEnv ?? []),
  ...(RELEASE_ENVIRONMENT_CONTRACT.optionalEdgePrivateEnv ?? []),
];

function printHelp() {
  console.log(`Usage: node scripts/write-release-env.mjs [options]

Write ${RELEASE_ENVIRONMENT_CONTRACT.profileFile} from the current process environment.

Options:
  --output <path>  Output dotenv path (default ${RELEASE_ENVIRONMENT_CONTRACT.profileFile}).
  --force          Overwrite an existing output file.
  --check          Validate and print a safe summary without writing.
  -h, --help       Show this help.
`);
}

function parseArgs(argv) {
  const settings = {
    outputPath: RELEASE_ENVIRONMENT_CONTRACT.profileFile,
    overwrite: false,
    check: false,
    help: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    switch (arg) {
      case '--output':
        index += 1;
        if (!argv[index]) {
          throw new Error('--output requires a path');
        }
        settings.outputPath = argv[index];
        break;
      case '--force':
        settings.overwrite = true;
        break;
      case '--check':
        settings.check = true;
        break;
      case '--help':
      case '-h':
        settings.help = true;
        break;
      default:
        throw new Error(`Unsupported release env writer option: ${arg}`);
    }
  }

  return settings;
}

function buildReleaseEnvFilePlan({
  env = process.env,
  outputPath = RELEASE_ENVIRONMENT_CONTRACT.profileFile,
  overwrite = false,
  existingFile = existsSync(outputPath),
} = {}) {
  if (isProtectedExampleOutput(outputPath)) {
    throw new Error(`${RELEASE_ENVIRONMENT_CONTRACT.exampleFile} is a checked-in template and cannot be used as release env writer output`);
  }

  if (existingFile && !overwrite) {
    throw new Error(`${outputPath} already exists; pass --force to overwrite it`);
  }

  const generatedEnv = buildClawRouterReleaseGeneratedEnv({
    env,
    workspaceRoot: WORKSPACE_ROOT,
  });
  const releaseEnvPartial = { ...generatedEnv };
  for (const name of CONTRACT_VARIABLES) {
    releaseEnvPartial[name] = String(env[name] ?? releaseEnvPartial[name] ?? '').trim();
  }
  for (const name of OPTIONAL_CONTRACT_VARIABLES) {
    const value = String(env[name] ?? releaseEnvPartial[name] ?? '').trim();
    if (value) {
      releaseEnvPartial[name] = value;
    }
  }
  const releaseEnv = completeReleaseEnvKeyOrder(releaseEnvPartial, generatedEnv);

  const issues = releaseEnvironmentIssues(releaseEnv);
  if (issues.length > 0) {
    throw new Error(`release environment contract is not satisfied: ${issues.join('; ')}`);
  }

  const content = [
    '# Generated by node scripts/write-release-env.mjs. Do not commit this file.',
    ...CLAW_ROUTER_RELEASE_ENV_KEY_ORDER.map(
      (name) => `${name}=${quoteDotenvValue(releaseEnv[name] ?? '')}`,
    ),
    ...Object.keys(releaseEnv)
      .filter((name) => !CLAW_ROUTER_RELEASE_ENV_KEY_ORDER.includes(name))
      .map((name) => `${name}=${quoteDotenvValue(releaseEnv[name])}`),
    '',
  ].join('\n');

  return {
    outputPath,
    content,
    safeSummary: `release env file would be written with ${Object.keys(releaseEnv).length} release profile variables`,
  };
}

function isProtectedExampleOutput(outputPath) {
  const resolvedOutputPath = path.resolve(outputPath);
  const resolvedExamplePath = path.resolve(WORKSPACE_ROOT, RELEASE_ENVIRONMENT_CONTRACT.exampleFile);
  return resolvedOutputPath === resolvedExamplePath;
}

function quoteDotenvValue(value) {
  return `"${String(value)
    .replaceAll('\\', '\\\\')
    .replaceAll('"', '\\"')
    .replaceAll('\r', '\\r')
    .replaceAll('\n', '\\n')}"`;
}

async function writeReleaseEnvFile(plan) {
  const outputDirectory = path.dirname(path.resolve(plan.outputPath));
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(plan.outputPath, plan.content, { encoding: 'utf8', flag: 'wx' });
}

async function main() {
  const settings = parseArgs(process.argv.slice(2));
  if (settings.help) {
    printHelp();
    return;
  }

  const plan = buildReleaseEnvFilePlan({
    env: process.env,
    outputPath: settings.outputPath,
    overwrite: settings.check || settings.overwrite,
  });

  if (!settings.check) {
    if (settings.overwrite && existsSync(settings.outputPath)) {
      await writeFile(settings.outputPath, plan.content, { encoding: 'utf8' });
    } else {
      await writeReleaseEnvFile(plan);
    }
  }

  const action = settings.check ? 'validated' : 'written';
  console.log(`[release-env] ${action}: ${plan.outputPath}`);
  console.log(`[release-env] ${plan.safeSummary}`);
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replaceAll('\\', '/'))) {
  main().catch((error) => {
    console.error(`[release-env] ${error.message}`);
    process.exit(1);
  });
}

export {
  CONTRACT_VARIABLES,
  OPTIONAL_CONTRACT_VARIABLES,
  buildReleaseEnvFilePlan,
  isProtectedExampleOutput,
  parseArgs,
  quoteDotenvValue,
  writeReleaseEnvFile,
};
