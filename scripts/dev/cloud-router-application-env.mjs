export function buildCloudRouterBrowserDevelopmentGeneratedEnv({
  env = process.env,
  workspaceRoot = DEFAULT_REPOSITORY_ROOT,
  portalRuntimeEnv = {},
  deploymentProfile = 'standalone',
} = {}) {
  const manifest = readApplicationManifest(workspaceRoot);
  const manifestAppId = normalizeText(manifest?.app?.key) ?? 'sdkwork-cloudrouter';
  const pickedPortalRuntimeEnv = pickBrowserDevelopmentPortalRuntimeEnv(portalRuntimeEnv);
  const generated = {
    [CLOUD_ROUTER_LIFECYCLE_ENV_KEYS.configProfile]: 'dev',
    [CLOUD_ROUTER_LIFECYCLE_ENV_KEYS.environment]: 'development',
    [CLOUD_ROUTER_LIFECYCLE_ENV_KEYS.deploymentProfile]: deploymentProfile,
    [CLOUD_ROUTER_LIFECYCLE_ENV_KEYS.runtimeTarget]: 'browser',
    [CLOUD_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.openApi]: resolveBrowserDevProxyOrigin(
      { ...env, ...pickedPortalRuntimeEnv },
      CLOUD_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.openApi,
      DEFAULT_DEV_PROXY_GATEWAY_TARGET,
    ),
    [CLOUD_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.backendApi]: resolveBrowserDevProxyOrigin(
      { ...env, ...pickedPortalRuntimeEnv },
      CLOUD_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.backendApi,
      DEFAULT_DEV_PROXY_GATEWAY_TARGET,
    ),
    [CLOUD_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.appApi]: resolveBrowserDevProxyOrigin(
      { ...env, ...pickedPortalRuntimeEnv },
      CLOUD_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.appApi,
      DEFAULT_DEV_PROXY_GATEWAY_TARGET,
    ),
    ...CLOUD_ROUTER_BROWSER_DEVELOPMENT_DEFAULT_VITE_ENV,
    VITE_SDKWORK_APP_ID: manifestAppId,
  };

  // The renderer's IAM app identity is the installation's deploy application
  // anchor; the build projects it so no renderer carries a compiled-in id. The
  // renderer fails closed when the projection is absent, so an unset anchor here
  // is not repaired with the retired IAM runtime app id.
  const deployApplicationId = resolveCloudRouterBrowserDeployApplicationId({
    env,
    workspaceRoot,
    deploymentProfile,
    environment: 'development',
  });
  if (deployApplicationId) {
    generated[CLOUD_ROUTER_BROWSER_DEPLOY_APPLICATION_ID_KEY] = deployApplicationId;
  }

  for (const key of Object.keys(CLOUD_ROUTER_BROWSER_DEVELOPMENT_DEFAULT_VITE_ENV)) {
    const value = normalizeText(pickedPortalRuntimeEnv[key]) ?? normalizeText(env[key]);
    if (value) {
      generated[key] = value;
    }
  }

  // dev:cloud: bind the Vite dev surface to the local platform API gateway
  // (sdkwork-api-cloud-gateway, SDKWORK_LOCAL_PLATFORM_API_GATEWAY_HTTP_URL)
  // instead of any api-dev.<base-domain> edge.
  const localPlatformApiGatewayHttpUrl = deploymentProfile === 'cloud'
    ? normalizeText(env[CLOUD_ROUTER_LOCAL_PLATFORM_API_GATEWAY_ENV_KEY])
    : undefined;

  return alignCloudLocalGatewayBrowserDevelopmentEnv(
    alignStandaloneSameOriginBrowserSdkRuntimeEnv(generated),
    { localPlatformApiGatewayHttpUrl },
  );
}

