export function ensureCloudRouterEnvForLifecycle(lifecycle, options = {}) {
  const normalized = String(lifecycle ?? '').trim().toLowerCase();
  switch (normalized) {
    case 'dev':
    case 'development':
      return {
        development: ensureCloudRouterBrowserDevelopmentEnv(options),
      };
    case 'build':
    case 'production':
      return {
        production: ensureCloudRouterBrowserProductionEnv(options),
      };
    case 'start':
    case 'release':
    case 'all':
      return {
        release: ensureCloudRouterReleaseEnv(options),
        production: ensureCloudRouterBrowserProductionEnv(options),
      };
    default:
      throw new Error(
        `unsupported lifecycle "${lifecycle}"; expected dev, build, start, or all`,
      );
  }
}

export function ensureCloudRouterEnvForProfile(profile, options = {}) {
  const normalized = String(profile ?? '').trim().toLowerCase();
  switch (normalized) {
    case 'development':
      return ensureCloudRouterBrowserDevelopmentEnv(options);
    case 'production':
      return ensureCloudRouterBrowserProductionEnv(options);
    case 'release':
      return ensureCloudRouterReleaseEnv(options);
    default:
      throw new Error(
        `unsupported profile "${profile}"; expected development, production, or release`,
      );
  }
}

function parseCliArgs(argv = []) {
  const options = {
    workspaceRoot: DEFAULT_REPOSITORY_ROOT,
    profile: 'development',
    dryRun: false,
    help: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    switch (arg) {
      case '--workspace-root':
        options.workspaceRoot = path.resolve(argv[index + 1] ?? options.workspaceRoot);
        index += 1;
        break;
      case '--profile':
        options.profile = argv[index + 1] ?? options.profile;
        index += 1;
        break;
      case '--dry-run':
        options.dryRun = true;
        break;
      case '--help':
      case '-h':
        options.help = true;
        break;
      default:
        throw new Error(`unknown option: ${arg}`);
    }
  }

  return options;
}

function printHelp() {
  console.log(`Usage: node scripts/dev/cloud-router-application-env.mjs [options]

Ensures SDKWork-standard host-local env files for Cloud Router profiles.

Profiles:
  development  apps/sdkwork-cloudrouter-pc/.env.standalone.development
  production   apps/sdkwork-cloudrouter-pc/.env.standalone.production
  release      .env.standalone.production

Options:
  --workspace-root <path>  Repository root
  --profile <development|production|release>
  --dry-run                Resolve merged env without writing files
  --help, -h               Show this help
`);
}

function main() {
  let options;
  try {
    options = parseCliArgs(process.argv.slice(2));
  } catch (error) {
    console.error(`[cloud-router-application-env] ${error.message}`);
    printHelp();
    process.exit(1);
  }

  if (options.help) {
    printHelp();
    process.exit(0);
  }

  const profile = String(options.profile).trim().toLowerCase();
  let result;
  try {
    result = ensureCloudRouterEnvForProfile(profile, {
      workspaceRoot: options.workspaceRoot,
      dryRun: options.dryRun,
    });
  } catch (error) {
    console.error(`[cloud-router-application-env] ${error.message}`);
    process.exit(1);
  }

  console.log('[cloud-router-application-env] application env ready');
  console.log(JSON.stringify({
    profile,
    profileFilePath: result.profileFilePath,
    changed: result.changed,
    created: result.created,
    keys: Object.keys(result.mergedEnv),
  }, null, 2));
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  main();
}
