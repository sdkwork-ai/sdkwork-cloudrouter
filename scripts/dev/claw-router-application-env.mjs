export function buildClawRouterBrowserDevelopmentGeneratedEnv({
  env = process.env,
  workspaceRoot = DEFAULT_REPOSITORY_ROOT,
  portalRuntimeEnv = {},
  deploymentProfile = 'standalone',
} = {}) {
  const manifest = readApplicationManifest(workspaceRoot);
  const manifestAppId = normalizeText(manifest?.app?.key) ?? 'sdkwork-clawrouter';
  const pickedPortalRuntimeEnv = pickBrowserDevelopmentPortalRuntimeEnv(portalRuntimeEnv);
  const generated = {
    [CLAW_ROUTER_LIFECYCLE_ENV_KEYS.configProfile]: 'dev',
    [CLAW_ROUTER_LIFECYCLE_ENV_KEYS.environment]: 'development',
    [CLAW_ROUTER_LIFECYCLE_ENV_KEYS.deploymentProfile]: deploymentProfile,
    [CLAW_ROUTER_LIFECYCLE_ENV_KEYS.runtimeTarget]: 'browser',
    [CLAW_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.openApi]: resolveBrowserDevProxyOrigin(
      { ...env, ...pickedPortalRuntimeEnv },
      CLAW_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.openApi,
      DEFAULT_DEV_PROXY_GATEWAY_TARGET,
    ),
    [CLAW_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.backendApi]: resolveBrowserDevProxyOrigin(
      { ...env, ...pickedPortalRuntimeEnv },
      CLAW_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.backendApi,
      DEFAULT_DEV_PROXY_GATEWAY_TARGET,
    ),
    [CLAW_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.appApi]: resolveBrowserDevProxyOrigin(
      { ...env, ...pickedPortalRuntimeEnv },
      CLAW_ROUTER_BROWSER_DEV_PROXY_ENV_KEYS.appApi,
      DEFAULT_DEV_PROXY_GATEWAY_TARGET,
    ),
    ...CLAW_ROUTER_BROWSER_DEVELOPMENT_DEFAULT_VITE_ENV,
    VITE_SDKWORK_APP_ID: manifestAppId,
  };

  for (const key of Object.keys(CLAW_ROUTER_BROWSER_DEVELOPMENT_DEFAULT_VITE_ENV)) {
    const value = normalizeText(pickedPortalRuntimeEnv[key]) ?? normalizeText(env[key]);
    if (value) {
      generated[key] = value;
    }
  }

  return generated;
}

