export function ensureClawRouterReleaseEnv({
  workspaceRoot = DEFAULT_REPOSITORY_ROOT,
  env = process.env,
  deploymentProfile = 'standalone',
  runtimeTarget = 'server',
  dryRun = false,
} = {}) {
  const profileFilePath = path.join(workspaceRoot, '.env.release');
  const existingBeforeEnsure = sanitizeReleaseHostEnvRecord(loadEnvFile(profileFilePath));
  const generatedEnv = buildClawRouterReleaseGeneratedEnv({
    env: { ...existingBeforeEnsure, ...env },
    workspaceRoot,
    deploymentProfile,
    runtimeTarget,
  });
  const result = ensureApplicationEnv({
    workspaceRoot,
    runtimeTarget: 'server',
    configProfile: 'release',
    generatedEnv,
    keyOrder: CLAW_ROUTER_RELEASE_ENV_KEY_ORDER,
    headerLines: [...RELEASE_ENV_HEADER],
    // Resolve without persisting unsanitized values from an existing profile.
    dryRun: true,
  });
  const sanitizedMergedEnv = normalizeClawRouterLifecycleEnvRecord(
    sanitizeReleaseHostEnvRecord(completeReleaseEnvKeyOrder(result.mergedEnv, generatedEnv)),
    generatedEnv,
  );
  const formattedContent = formatEnvFileContent(sanitizedMergedEnv, {
    headerLines: [...RELEASE_ENV_HEADER],
    keyOrder: CLAW_ROUTER_RELEASE_ENV_KEY_ORDER,
    keyComments: CLAW_ROUTER_RELEASE_EDGE_ENV_KEY_COMMENTS,
    sectionBreaks: RELEASE_ENV_SECTIONS,
  });
  const sanitizedChanged = envFileChanged(result.mergedEnv, sanitizedMergedEnv)
    || envFileChanged(existingBeforeEnsure, sanitizedMergedEnv);
  const existingContent = existsSync(result.profileFilePath)
    ? readFileSync(result.profileFilePath, 'utf8')
    : '';
  const formattedChanged = existingContent !== formattedContent;
  if (!dryRun && (result.changed || sanitizedChanged || formattedChanged)) {
    mkdirSync(path.dirname(result.profileFilePath), { recursive: true });
    writeFileSync(result.profileFilePath, formattedContent, 'utf8');
  }
  return {
    ...result,
    mergedEnv: sanitizedMergedEnv,
    changed: result.changed || sanitizedChanged || formattedChanged,
  };
}

