function normalizeText(value) {
  const normalized = String(value ?? '').trim();
  return normalized || undefined;
}

function completeReleaseEnvKeyOrder(mergedEnv, generatedEnv) {
  const complete = { ...mergedEnv };
  delete complete.SDKWORK_ACCESS_TOKEN;
  for (const key of CLAW_ROUTER_RELEASE_ENV_KEY_ORDER) {
    if (!Object.prototype.hasOwnProperty.call(complete, key)) {
      complete[key] = generatedEnv[key] ?? '';
    }
  }
  return complete;
}

export { completeReleaseEnvKeyOrder };

function ensureClawRouterBootstrapLocalEnv({
  applicationRoot,
  configProfile = 'development',
  credentials = {},
  dryRun = false,
} = {}) {
  const bootstrapLocalPath = path.join(
    applicationRoot,
    `.env.${configProfile}.bootstrap.local`,
  );
  const bootstrapEnv = {
    SDKWORK_ACCESS_TOKEN: normalizeText(credentials.SDKWORK_ACCESS_TOKEN) ?? '',
  };
  const existing = loadEnvFile(bootstrapLocalPath);
  const changed = envFileChanged(existing, bootstrapEnv);
  if (!dryRun && changed) {
    mkdirSync(path.dirname(bootstrapLocalPath), { recursive: true });
    writeFileSync(
      bootstrapLocalPath,
      formatEnvFileContent(bootstrapEnv, {
        headerLines: [
          '# SDKWork private bootstrap credentials (gitignored).',
          '# Generated by scripts/dev/claw-router-application-env.mjs.',
        ],
        keyOrder: ['SDKWORK_ACCESS_TOKEN'],
      }),
      'utf8',
    );
  }
  return { bootstrapLocalPath, changed, bootstrapEnv };
}

export function buildClawRouterCredentialEntryBootstrapEnv({
  env = process.env,
  workspaceRoot = DEFAULT_REPOSITORY_ROOT,
  environment,
  deploymentMode = 'local',
  sessionId = 'bootstrap-local-development',
  runtimeTarget = 'browser',
} = {}) {
  if (environment !== 'development') {
    throw new Error('local bootstrap token generation requires an explicit development lifecycle');
  }
  const manifest = readApplicationManifest(workspaceRoot);
  return buildBootstrapAccessTokenEnvRecord(env.SDKWORK_ACCESS_TOKEN, {
    manifest,
    environment,
    deploymentMode,
    runtimeTarget,
    sessionId,
  });
}

